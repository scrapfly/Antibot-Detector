/**
 * Canonical badge constants and helpers.
 * Shared across popup and background contexts.
 */

const BADGE = {
    TEXT: {
        LOADING: '\u280b',
        DISABLED: 'OFF',
        // Paused domains show PAUSED_ICON instead of badge text: badge glyphs use
        // the browser's UI font and rendered as a merged block or hairlines.
        BLACKLISTED: '',
        INTERRUPTED: '\u21BB',
        CLEARED: '\u21BB',
        CLEAN: '',
        EMPTY: ''
    },

    TEXT_COLORS: {
        BLACKLISTED: '#7dd3fc',
        // Fixed white: the luminance rule picks black on the loading blue,
        // which turns the thin braille spinner into a dark smudge.
        LOADING: '#ffffff'
    },

    COLORS: {
        LOW: '#22c55e',
        MEDIUM: '#f59e0b',
        HIGH: '#ef4444',
        // Deep enough for white text (5.2:1), still clearly "working" blue
        LOADING: '#2563eb',
        DISABLED: '#f97316',
        BLACKLISTED: '#1e293b',
        CLEARED: '#6B7280',
        CLEAN: '#22c55e'
    },

    // Braille frames for the animated "analyzing" badge spinner (driven from the
    // background while a detection runs). LOADING above is frame 0.
    SPINNER_FRAMES: ['⠋', '⠙', '⠹', '⠸', '⠼', '⠴', '⠦', '⠧', '⠇', '⠏'],

    // Toolbar icons. PAUSED_ICON is the dimmed logo with a navy pause tile,
    // generated by scripts/generate-paused-icons.js from the normal icon.
    ICON: { 16: 'icons/icon16.png', 32: 'icons/icon32.png' },
    PAUSED_ICON: { 16: 'icons/paused16.png', 32: 'icons/paused32.png' }
};

// True if a badge text represents the "loading/analyzing" state — either the
// static LOADING glyph or any animated spinner frame. Use this instead of
// `text === BADGE.TEXT.LOADING` so checks work while the spinner is cycling.
function isLoadingBadgeText(text) {
    const t = (text || '').trim();
    return t === BADGE.TEXT.LOADING || BADGE.SPINNER_FRAMES.indexOf(t) !== -1;
}

// Chrome 110+ supports explicit badge text colors. Supply the actual normal
// background on restoration: omitting color is rejected by Chromium's API.
async function setBadgeTextColor(tabId, blacklisted = false, backgroundColor = BADGE.COLORS.CLEAN) {
    if (typeof chrome === 'undefined' || typeof chrome.action?.setBadgeTextColor !== 'function') return;
    try {
        let color = BADGE.TEXT_COLORS.BLACKLISTED;
        if (!blacklisted) {
            // Badge settings use hex colors. Also accept Chrome's RGB(A) arrays.
            let rgb = Array.isArray(backgroundColor) ? backgroundColor.slice(0, 3) : null;
            const hex = typeof backgroundColor === 'string' ? backgroundColor.match(/^#([\da-f]{3}|[\da-f]{6}|[\da-f]{8})$/i) : null;
            if (hex) {
                const value = hex[1].length === 3 ? hex[1].split('').map((c) => c + c).join('') : hex[1];
                rgb = [0, 2, 4].map((offset) => parseInt(value.slice(offset, offset + 2), 16));
            }
            if (!rgb && typeof chrome.action.getBadgeBackgroundColor === 'function') {
                rgb = await chrome.action.getBadgeBackgroundColor({ tabId });
            }
            if (rgb) {
                const linear = rgb.slice(0, 3).map((channel) => {
                    const value = channel / 255;
                    return value <= 0.04045 ? value / 12.92 : Math.pow((value + 0.055) / 1.055, 2.4);
                });
                const luminance = linear[0] * 0.2126 + linear[1] * 0.7152 + linear[2] * 0.0722;
                color = luminance > 0.179 ? '#000000' : '#ffffff';
            }
        }
        await chrome.action.setBadgeTextColor({ tabId, color });
    } catch (_) {
        // Older browsers or closed tabs must not prevent the badge state update.
    }
}

// Per-tab toolbar icon: the paused tile on excluded domains, the normal logo
// everywhere else. Callers on a path that may leave the paused state call
// this too, so a tab never keeps the paused icon after an unblock or toggle.
async function setPausedIcon(tabId, paused) {
    if (typeof chrome === 'undefined' || typeof chrome.action?.setIcon !== 'function' || tabId == null) return;
    try {
        await chrome.action.setIcon({ tabId, path: paused ? BADGE.PAUSED_ICON : BADGE.ICON });
    } catch (_) {
        // Closed tabs must not prevent the badge state update.
    }
}

const badgeGlobal = typeof globalThis !== 'undefined'
    ? globalThis
    : (typeof self !== 'undefined' ? self : (typeof window !== 'undefined' ? window : null));

if (badgeGlobal) {
    badgeGlobal.BADGE = BADGE;
    badgeGlobal.setBadgeTextColor = setBadgeTextColor;
    badgeGlobal.isLoadingBadgeText = isLoadingBadgeText;
    badgeGlobal.setPausedIcon = setPausedIcon;
}

